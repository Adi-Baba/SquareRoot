class UndecidedError(RuntimeError):
    """A comparison stayed undecided past the precision cap."""


# --------------------------------------------------------------------------
# Exact arithmetic in L = Q(sqrt(a_1), sqrt(a_j)).
#
# An element is a 4-tuple of Fractions in the ordered basis
#     ( 1 , sqrt(a_1) , sqrt(a_j) , sqrt(a_1 a_j) ).
# --------------------------------------------------------------------------

class Elem(NamedTuple):
    c0: Fraction
    c1: Fraction
    c2: Fraction
    c3: Fraction


def zero() -> Elem:
    z = Fraction(0)
    return Elem(z, z, z, z)


def elem_add(x: Elem, y: Elem) -> Elem:
    return Elem(x.c0 + y.c0, x.c1 + y.c1, x.c2 + y.c2, x.c3 + y.c3)


def elem_sub(x: Elem, y: Elem) -> Elem:
    return Elem(x.c0 - y.c0, x.c1 - y.c1, x.c2 - y.c2, x.c3 - y.c3)


def elem_neg(x: Elem) -> Elem:
    return Elem(-x.c0, -x.c1, -x.c2, -x.c3)


def elem_mul(x: Elem, y: Elem, a1: int, aj: int) -> Elem:
    """
    Product in the basis (1, sqrt(a_1), sqrt(a_j), sqrt(a_1 a_j)).

    Using g = sqrt(a_1 a_j): g^2 = a_1 a_j, s = sqrt(a_1), t = sqrt(a_j),
    s*t = g, s*g = a_1 t, t*g = a_j s.
    """
    x0, x1, x2, x3 = x
    y0, y1, y2, y3 = y
    return Elem(
        x0 * y0 + a1 * x1 * y1 + aj * x2 * y2 + a1 * aj * x3 * y3,
        x0 * y1 + x1 * y0 + aj * x2 * y3 + aj * x3 * y2,
        x0 * y2 + x2 * y0 + a1 * x1 * y3 + a1 * x3 * y1,
        x0 * y3 + x3 * y0 + x1 * y2 + x2 * y1,
    )


def elem_is_zero(x: Elem) -> bool:
    return x.c0 == 0 and x.c1 == 0 and x.c2 == 0 and x.c3 == 0


def scale(c: int, x: Elem) -> Elem:
    f = Fraction(c)
    return Elem(f * x.c0, f * x.c1, f * x.c2, f * x.c3)


def conjugates(x: Elem) -> List[Elem]:
    """The four Q-embeddings of L: flip sqrt(a_1) and/or sqrt(a_j)."""
    x0, x1, x2, x3 = x
    return [
        Elem(x0, x1, x2, x3),
        Elem(x0, -x1, x2, -x3),
        Elem(x0, x1, -x2, -x3),
        Elem(x0, -x1, -x2, x3),
    ]


def field_norm(x: Elem, a1: int, aj: int) -> Fraction:
    """
    N_{L/Q}(x), exact.  For x in Z this is the integer norm; the return type
    is Fraction because the engine scales elements by 2*a_1.
    """
    acc = Elem(Fraction(1), Fraction(0), Fraction(0), Fraction(0))
    for c in conjugates(x):
        acc = elem_mul(acc, c, a1, aj)
    return acc.c0


# --------------------------------------------------------------------------
# Pell data, indexed so that k IS the exponent.
# --------------------------------------------------------------------------

class PellPoint(NamedTuple):
    k: int
    pk: int
    qk: int


def eps_power(a1: int, k: int) -> PellPoint:
    """
    eps^k = P_k + Q_k sqrt(a_1) with eps = 1 + sqrt(a_1).

    Built by the exact recurrence (P,Q) -> (P + a_1*Q, P + Q), which follows
    from (P + Q sqrt a)(1 + sqrt a) = (P + a Q) + (P + Q) sqrt a.  So the
    index is the exponent by construction and cannot drift, unlike a
    continued-fraction list.  Verified for a_1 = 2: k=1 -> (2,1),
    k=2 -> (6,4), k=3 -> (14,10).
    """
    if k < 0:
        raise ValueError("k must be non-negative")
    p, q = 1, 0
    for _ in range(k):
        p, q = p + a1 * q, p + q
    return PellPoint(k, p, q)


# --------------------------------------------------------------------------
# Layer 1 -- the recurrence, and the nearest integer m_k.
# --------------------------------------------------------------------------

def z_of_x(a1: int, aj: int, k: int) -> Elem:
    """
    z_k := 2*a_1 * x_k = a_1*Q_k*sqrt(a_j) + P_k*sqrt(a_1*a_j).

    Derivation: beta_j = sqrt(a_1 a_j)/(2 a_1) and eps^k = P_k + Q_k sqrt(a_1),
    so 2 a_1 x_k = sqrt(a_1 a_j) P_k + sqrt(a_1 a_j) Q_k sqrt(a_1)
                  = P_k sqrt(a_1 a_j) + a_1 Q_k sqrt(a_j).
    """
    pt = eps_power(a1, k)
    return Elem(
        Fraction(0), Fraction(0),
        Fraction(a1 * pt.qk), Fraction(pt.pk),
    )


def nearest_integer(a1: int, aj: int, k: int, bits: int = 64) -> int:
    """
    m_k = nint(x_k), decided exactly.

    |x_k - m_k| <= 1/2  =>  |z_k - 2 a_1 m_k| <= a_1, so 2 a_1 m_k is the
    unique multiple of 2*a_1 inside [z_k - a_1, z_k + a_1].  We bracket z_k
    with certified_bracket (integer arithmetic), read off the candidate, then
    CONFIRM it with a second certified bracket; if either certificate is too
    coarse to decide we double the precision rather than guess.
    """
    pt = eps_power(a1, k)
    terms_z = [(a1 * pt.qk, aj), (pt.pk, a1 * aj)]
    agg_z, _ = SF.decompose_and_aggregate(terms_z)
    cap = SE.DEFAULT_MAX_BITS
    while True:
        try:
            lo, hi = SE.certified_bracket(agg_z, bits)
        except SE.SignUnknownError:
            if bits >= cap:
                raise UndecidedError(f"m_{k} undecided at {bits} bits")
            bits *= 2
            continue
        flo = (lo + a1) // (2 * a1)
        fhi = (hi + a1) // (2 * a1)
        if flo == fhi:
            cand = int(flo)
            # CONFIRM exactly: |2 a_1 x_k - 2 a_1 cand| <= a_1
            agg_c, _ = SF.decompose_and_aggregate(
                [(-2 * a1 * cand, 1)] + terms_z)
            try:
                clo, chi = SE.certified_bracket(agg_c, bits)
            except SE.SignUnknownError:
                clo, chi = None, None
            if clo is not None and -a1 <= clo and chi <= a1:
                return cand
        if bits >= cap:
            raise UndecidedError(f"m_{k} not confirmed at {bits} bits")
        bits *= 2


# --------------------------------------------------------------------------
# Layer 2 -- the norm of y_k = m_k - x_k.
# --------------------------------------------------------------------------

def y_of(a1: int, aj: int, k: int, m: Optional[int] = None) -> Elem:
    """y_k = m_k - x_k, in L, exactly."""
    if m is None:
        m = nearest_integer(a1, aj, k)
    zk = z_of_x(a1, aj, k)
    base = Elem(Fraction(2 * a1 * m), Fraction(0), Fraction(0), Fraction(0))
    return elem_sub(base, zk)


# --------------------------------------------------------------------------
# Layer 3 -- the invariant, and its recorded degeneracy.
# --------------------------------------------------------------------------

def q_form(u: Elem, v: Elem, a1: int, aj: int) -> Elem:
    """Q(u,v) = v^2 - 2uv - u^2."""
    vv = elem_mul(v, v, a1, aj)
    uv = scale(2, elem_mul(u, v, a1, aj))
    uu = elem_mul(u, u, a1, aj)
    return elem_sub(elem_sub(vv, uv), uu)


def q_factorises(u: Elem, v: Elem, a1: int, aj: int) -> bool:
    """
    Check Q(u,v) == (v - eps u)(v - eps' u) on arbitrary u,v in L.

    Exact identity: eps + eps' = 2 and eps*eps' = -1.
    """
    pt = eps_power(a1, 1)
    eps = Elem(Fraction(pt.pk), Fraction(pt.qk), Fraction(0), Fraction(0))
    epsp = Elem(Fraction(pt.pk), Fraction(-pt.qk), Fraction(0), Fraction(0))
    lhs = q_form(u, v, a1, aj)
    fa = elem_sub(v, elem_mul(eps, u, a1, aj))
    fb = elem_sub(v, elem_mul(epsp, u, a1, aj))
    rhs = elem_mul(fa, fb, a1, aj)
    return elem_is_zero(elem_sub(lhs, rhs))


# --------------------------------------------------------------------------
# Layer 4 -- the integer obstruction c_k = m_{k+1} - eps*m_k.
# --------------------------------------------------------------------------

def c_of(a1: int, k: int, m_k: int, m_k1: int) -> Tuple[int, int]:
    """
    c_k = m_{k+1} - eps m_k = (m_{k+1} - m_k) + (-m_k) sqrt(a_1).

    (Substituting x_k = m_k - y_k and x_{k+1} = eps x_k gives
     c_k = y_{k+1} - eps y_k, so |c_k| <= d_{k+1} + eps d_k.)

    Returned as the integer pair (u, v) with c_k = u + v sqrt(a_1), so that
    N(c_k) = u^2 - a_1 v^2 is an integer and can be compared exactly.
    """
    return (m_k1 - m_k, -m_k)


def norm_of_c(a1: int, uv: Tuple[int, int]) -> int:
    u, v = uv
    return u * u - a1 * v * v


# --------------------------------------------------------------------------
# Reporting rows.  Magnitudes here use Fraction -> float ONCE, in the caller,
# so the library above stays exact; see __main__ for the log arithmetic.
# --------------------------------------------------------------------------

class MeasureRow(NamedTuple):
    k: int
    pk: int
    qk: int
    m: int
    norm_y_scaled: int          # N_{L/Q}(2 a_1 y_k), an integer
    y_scaled: Tuple[int, int, int, int]   # coefficients of 2 a_1 y_k
    bits_used: int


def measure_row(a1: int, aj: int, k: int, bits: int = 64) -> MeasureRow:
    m = nearest_integer(a1, aj, k, bits)
    y = y_of(a1, aj, k, m)
    nrm = field_norm(y, a1, aj)
    num = nrm.numerator
    den = nrm.denominator
    if den != 1:
        raise UndecidedError(f"N(2 a_1 y_{k}) is not an integer: {nrm}")
    pt = eps_power(a1, k)
    ysc = tuple(int(c) for c in (y.c0, y.c1, y.c2, y.c3))
    if any(c.denominator != 1 for c in (y.c0, y.c1, y.c2, y.c3)):
        raise UndecidedError(f"2 a_1 y_{k} has non-integer coefficients")
    return MeasureRow(k, pt.pk, pt.qk, m, num, ysc, bits)


def invariant_row(a1: int, aj: int, k: int) -> bool:
    """
    True iff I_k = x_{k+1}^2 - 2 x_k x_{k+1} - x_k^2 vanishes identically.

    Computed on 2*a_1*x_k and 2*a_1*x_{k+1}; a change of scale multiplies I by
    a positive square factor, so vanishing is unaffected.
    """
    zk = z_of_x(a1, aj, k)
    zk1 = z_of_x(a1, aj, k + 1)
    i = q_form(zk, zk1, a1, aj)
    return elem_is_zero(i)


def integrality_row(a1: int, aj: int, k: int) -> Tuple[int, int, int, int]:
    """(u_k, v_k, N(c_k), m_{k+1}) for c_k = m_{k+1} - eps m_k."""
    m_k = nearest_integer(a1, aj, k)
    m_k1 = nearest_integer(a1, aj, k + 1)
    u, v = c_of(a1, k, m_k, m_k1)
    return (u, v, norm_of_c(a1, (u, v)), m_k1)


# --------------------------------------------------------------------------
# Track B -- the product level (Docs/37).
#
# The factorwise route of Docs/29 threw away the fact that every coordinate
# shares the SAME Pell pair (P_k, Q_k).  These helpers exploit that.
# --------------------------------------------------------------------------

def s1_exact(a1: int, k: int) -> int:
    """
    The a_1 coordinate is EXACT, not generic:  ||Q_k sqrt(a_1)|| = |eps'|^k.

    Because eps^k = P_k + Q_k sqrt(a_1) and eps'^k = P_k - Q_k sqrt(a_1),
    we get  Q_k sqrt(a_1) = P_k - eps'^k, so the distance from Q_k sqrt(a_1)
    to the integer P_k is exactly |eps'|^k.  (Docs/34 section 34.2 warns that
    eps' = -eps^{-1}, so |eps'|^k = eps^{-k} and eps'^k = (-1)^k eps^{-k};
    do not confuse eps' with eps^{-1}.)

    Returns the numerator of |eps'|^k in lowest terms together with the
    denominator of its height, as the exact pair (num, den) with
    |eps'|^k = num/den -- not needed; instead we return the SIGN-CONFIRMED
    fact that the nearest integer to Q_k sqrt(a_1) is P_k, by checking
    sign(P_k - Q_k sqrt(a_1)) == sign(eps'^k) and |...| < 1/2.
    """
    pt = eps_power(a1, k)
    # nearest integer to Q_k sqrt(a_1) must be P_k
    s = SE.exact_sign([(pt.pk, 1), (-pt.qk, a1)]).sign
    # eps'^k has the sign of eps' = 1 - sqrt(a1) < 0 raised to k
    expect = -1 if k % 2 else 1
    if s != expect:
        raise UndecidedError(f"s1 sign wrong at k={k}: {s} != {expect}")
    return pt.pk


def pair_integer(aj: int, ajp: int, mj: int, mjp: int) -> int:
    """
    I_{j,j'} = m_{j'}^2 a_j - m_j^2 a_{j'}, the integer behind the pair bound.

    Nonzero for distinct squarefree a_j != a_j' with m_j, m_{j'} integers,
    because I_{j,j'} = 0 would give m_{j'}^2 a_j = m_j^2 a_{j'}, i.e.
    a_j/a_{j'} = (m_j/m_{j'})^2 is a rational square, impossible for distinct
    squarefree radicands (unless both m vanish, which cannot happen for k > 0
    since m_k ~ beta_j eps^k).
    """
    return mjp * mjp * aj - mj * mj * ajp


def pair_bound_holds(a1: int, aj: int, ajp: int, k: int) -> bool:
    """
    Theorem 37.1, certified EXACTLY (no weakening, no dropped terms).

        |e_j| sqrt(a_j') + |e_j'| sqrt(a_j)  >=  1 / ( m_{j'} sqrt(a_j) + m_j sqrt(a_j') ).

    Write L_j := 2 a_1 e_j = a_1 Q_k sqrt(a_j) + P_k sqrt(a_1 a_j) - 2 a_1 m_j,
    so the claim is  ( |L_j| sqrt(a_j') + |L_j'| sqrt(a_j) ) ( m_j' sqrt(a_j)
    + m_j sqrt(a_j') )  >=  2 a_1.  Clearing the radicals gives the identity

      that product
        = sqrt(a_j a_j') ( |L_j| m_j' + |L_j'| m_j ) + a_j' |L_j| m_j
          + a_j |L_j'| m_j' ,

    and since |L| = sign(L) * L with the signs decided exactly, the whole
    left side is a linear form in {1, sqrt(a_j), sqrt(a_j'), sqrt(a_1 a_j),
    sqrt(a_1 a_j'), sqrt(a_j a_j')} -- six surds, no products of unknowns.
    certify > 0 against 2 a_1.

    An earlier version of this function proved only the weaker condition
    obtained by discarding |L_j'| sqrt(a_j); it failed 124 of 295 cases while
    the true inequality held in all of them.  Keeping every term is what makes
    the certificate valid.
    """
    import squarefree as SF

    mj = nearest_integer(a1, aj, k)
    mjp = nearest_integer(a1, ajp, k)
    if pair_integer(aj, ajp, mj, mjp) == 0:
        raise UndecidedError(f"I_(j,j') vanished at k={k}")
    pt = eps_power(a1, k)
    aqk, apk = a1 * pt.qk, pt.pk
    r_ajp, r_a1ajp, r_aja_jp = ajp, a1 * ajp, aj * ajp

    def sign_of(a_r, coef_q, coef_p, m):
        # a_r is the radicand of the coordinate whose sign we want.  It must be
        # a PARAMETER: an earlier version closed over `aj` and therefore
        # computed sign(L_j') inside Q(sqrt(a_1), sqrt(a_j)) instead of
        # Q(sqrt(a_1), sqrt(a_j')), which returned the wrong sign and made the
        # certificate fail 68 of 295 cases where the inequality held.
        agg, _ = SF.decompose_and_aggregate(
            [(coef_q, a_r), (coef_p, a1 * a_r), (-2 * a1 * m, 1)])
        return SE.exact_sign_from_aggregated(agg).sign

    sg_j = sign_of(aj, aqk, apk, mj)
    sg_jp = sign_of(ajp, aqk, apk, mjp)

    terms = [
        # T1 = sg_j m_jp sqrt(a_j a_j') L_j
        (sg_j * mjp * aqk * aj, r_ajp),
        (sg_j * mjp * apk * aj, r_a1ajp),
        (-sg_j * 2 * a1 * mj * mjp, r_aja_jp),
        # T2 = sg_j m_j a_j' L_j
        (sg_j * mj * ajp * aqk, aj),
        (sg_j * mj * ajp * apk, a1 * aj),
        (-sg_j * 2 * a1 * mj * mj * ajp, 1),
        # T3 = sg_jp m_jp a_j L_jp
        (sg_jp * mjp * aj * aqk, r_ajp),
        (sg_jp * mjp * aj * apk, r_a1ajp),
        (-sg_jp * 2 * a1 * mjp * mjp * aj, 1),
        # T4 = sg_jp m_j sqrt(a_j a_j') L_jp
        (sg_jp * mj * aqk * ajp, aj),
        (sg_jp * mj * apk * ajp, a1 * aj),
        (-sg_jp * 2 * a1 * mjp * mj, r_aja_jp),
        # subtract the right-hand side 2 a_1
        (-2 * a1, 1),
    ]
    agg, _ = SF.decompose_and_aggregate(terms)
    got = SE.exact_sign_from_aggregated(agg).sign
    if got == 0:
        raise UndecidedError(f"pair certificate exactly tight at k={k}")
    return got > 0
