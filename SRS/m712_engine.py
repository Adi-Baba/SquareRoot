"""
Research engine for M7.12 -- the trace-zero order-2 recurrence.

Docs/35 reduced M7.12 to a single question.  With eps = 1+sqrt(a_1),
eps' = 1-sqrt(a_1), rho = eps'/eps and beta_j = sqrt(a_j/a_1)/2, put

    x_k     = beta_j * eps^k ,
    x_{k+2} = 2 x_{k+1} + x_k ,        Tr_L(x_k) = 0 ,   L = Q(sqrt(a_1),sqrt(a_j)).

Known:    ||x_k||  >=  eps^(-3k) / (2 beta_j^3) =  exp(-3k log eps + O(1)).
          (NOT |rho|^{3k}: |rho| = |eps'/eps| = 0.1716 != eps^(-1) = |eps'| = 0.4142.)
Needed:   ||x_k||  >   theta_0^k                  =  exp(-k log eps/(3n(n-1))).
Gap:      a factor 9n(n-1) in the exponent.

The engine has four layers and is a DIAGNOSTIC, not a search for a magical
inequality.  Its job is to answer one question: which arithmetic quantity
systematically grows when ||x_k|| becomes unusually small?  Whatever that
quantity is, if it is integer- or norm-valued, it is the missing theorem.

    layer 1  recurrence   x_k, m_k = nint(x_k), d_k = ||x_k||
    layer 2  norm         N_L(y_k) with y_k = m_k - x_k;  slack R_k, G_norm(k)
    layer 3  invariant    Q(u,v) = v^2 - 2uv - u^2 = (v - eps u)(v - eps' u)
    layer 4  integrality  c_k = m_{k+1} - eps m_k in Z[sqrt(a_1)], and N(c_k)

WHY LAYER 3 IS RECORDED AS DEGENERATE
-------------------------------------
The natural invariant of u_{k+2} = 2u_{k+1}+u_k is Q(u_k,u_{k+1}); one checks
Q(u_{k+1},u_{k+2}) = -Q(u_k,u_{k+1}), so it is ANTI-invariant, not invariant.
More importantly Q factors EXACTLY as (v-eps u)(v-eps' u), and for a pure
eigen-solution x_k = beta_j eps^k the first factor vanishes identically.  So
I_k = x_{k+1}^2 - 2 x_k x_{k+1} - x_k^2 is IDENTICALLY ZERO and carries no
information.  This module asserts that, so the degeneracy is a checked fact
rather than a silent dead layer.

The information that survives sits in the OTHER factor and in layer 4:
c_k = m_{k+1} - eps m_k is an element of Z[sqrt(a_1)] with
|c_k| <= d_{k+1} + eps d_k, and its norm is the integer
N(c_k) = (m_{k+1} - m_k)^2 - a_1 m_k^2.  Note the sign: since
y_k := m_k - x_k and x_{k+1} = eps x_k, one gets c_k = y_{k+1} - eps y_k
(NOT y_{k+1} + eps y_k).  Verified at k=10: y_11 - eps*y_10 =
0.296351 - 2.414214*0.183089 = -0.145663, and |c_10| = 0.145663.

WHY THIS IS EXACT
-----------------
Every decision -- the nearest integer m_k, the sign of any comparison, the
norms -- is integer or Fraction arithmetic.  Pell data is generated by
repeated exact multiplication rather than by a continued-fraction recursion,
which removes the index hazard of Docs/34 section 34.2: eps^k = P_k + Q_k
sqrt(a_1) holds with k literally the exponent, by construction.

Bracketing reuses signexact.certified_bracket, which is integer arithmetic
with a doubling loop; on an undecided instance we raise rather than guess.
This module is 100% exact: integer and Fraction arithmetic only, no float, no
Decimal, no math.sqrt anywhere.  tests/test_no_float.py lists it as a
DECISION_PATH module, which enforces that.  The measuring/reporting code --
everything that takes a logarithm -- lives in m712_report.py, which is listed
as a MEASUREMENT module with that reason.
"""

