"""
F1: the Pell family, its exact separation law, and the Möbius-CF correspondence.

CONSTRUCTION
------------
Fix a >= 2 and put alpha = a(a+1).  The continued fraction of sqrt(alpha) is
periodic from the start:

    sqrt(a(a+1)) = [a; 2, 2a, 2, 2a, 2, 2a, ...]

so its convergents p_n/q_n are generated by the recurrence in
`pell_convergents`.  The SRS instance is

    S_n = sqrt(p_n^2) - sqrt(alpha * q_n^2) = p_n - q_n * sqrt(alpha)

THE EXACT RESIDUE (proved below, and checked by `verify_theorem`)
---------------------------------------------------------------
    p_n^2 - alpha * q_n^2 = +1   for odd n
    p_n^2 - alpha * q_n^2 = -a   for even n

Both are exact integer identities, verified as such -- no floating point is
involved in the claim.  Two consequences, and these fix the sign outright:

    odd  n:  p_n^2 > alpha q_n^2  and p_n, q_n > 0   =>   S_n > 0
    even n:  p_n^2 < alpha q_n^2  and p_n, q_n > 0   =>   S_n < 0

SEPARATION LAW
--------------
Let D = p_n^2 - alpha q_n^2 (so |D| = 1 for odd n, a for even n) and
g = p_n + q_n sqrt(alpha).  Rationalising the denominator gives

    |S_n| = |p_n - q_n sqrt(alpha)| = |D| / g
    log2(1/|S_n|) = log2(g) - log2(|D|)

The input size is the bit length of the two radicands:

    N = log2(p_n^2) + log2(alpha q_n^2)
      = 2 log2 p_n + 2 log2 q_n + log2 alpha

Since q_n ~ p_n / sqrt(alpha), the log2 alpha terms cancel between
2 log2 q_n and + log2 alpha, leaving

    N/4 = log2 p_n + o(1)

and since g = p_n + q_n sqrt(alpha) = 2 p_n + o(1),

    log2(g) = log2 p_n + 1 + o(1) = N/4 + 1 + o(1)

Combining:

    log2(1/|S_n|) = N/4 + 1 - log2(|D|) + o(1)

so the ratio log2(1/|S_n|)/N tends to 1/4, and the exact corrections are

    odd  n:  N/4 + 1        (|D| = 1)   ratio above 1/4 by 1/N
    even n:  N/4 + 1 - log2 a  (|D| = a)  above, equal, or below per a

`verify_theorem` checks this identity numerically at every n, to a tolerance of
1e-3, which is the margin the o(1) term allows; the floor is far below any
digit anyone would quote.

This is a PROVED separation upper bound: |S_n| = 2^(-Theta(N)), so a
fixed-precision approximation cannot decide the sign in general.  The
certified decider in signexact.py handles it by refining the bracket until
the interval clears zero, and reports how many bits that took.
"""

from fractions import Fraction as F
from math import log2, sqrt
from typing import List, Tuple

__all__ = [
    "pell_convergents",
    "pell_residue",
    "expected_sign",
    "separation_identity",
    "log2_ratio_law",
    "exact_pell_identity",
    "mobius_iterates",
    "verify_theorem",
    "verify_separation_law",
    "SEPARATION_RATIO",
]

# The proved value of log2(1/|S_n|)/N as n -> infinity, on odd n.
SEPARATION_RATIO = 0.25


def _check_a(a: int) -> int:
    if not isinstance(a, int) or isinstance(a, bool):
        raise TypeError(f"a must be an int, got {a!r}")
    if a < 2:
        raise ValueError(f"a must be >= 2, got {a}")
    return a


def _check_n(n_max: int) -> int:
    if not isinstance(n_max, int) or isinstance(n_max, bool):
        raise TypeError(f"n_max must be an int, got {n_max!r}")
    if n_max < 0:
        raise ValueError(f"n_max must be >= 0, got {n_max}")
    return n_max


def pell_convergents(a: int, n_max: int) -> List[Tuple[int, int]]:
    """
    CF convergents (p_n, q_n) of sqrt(a(a+1)) for n = 0..n_max.

    sqrt(a(a+1)) = [a; 2, 2a, 2, 2a, ...], so a_1 = 2, a_2 = 2a, a_3 = 2, ...
    Index 0 is the integer part p_0/q_0 = a/1.

    Returns a list of n_max+1 pairs of ints.
    """
    _check_a(a)
    _check_n(n_max)

    p = [a, 2 * a + 1]
    q = [1, 2]
    for i in range(2, n_max + 1):
        a_i = 2 if i % 2 == 1 else 2 * a
        p.append(a_i * p[-1] + p[-2])
        q.append(a_i * q[-1] + q[-2])
    return list(zip(p, q))[:n_max + 1]


def exact_pell_identity(a: int, n: int) -> Tuple[int, int, int]:
    """
    Returns (p_n, q_n, p_n^2 - alpha q_n^2), all exact integers.

    The residue is +1 for odd n and -a for even n; see `pell_residue`.
    """
    _check_a(a)
    _check_n(n)
    alpha = a * (a + 1)
    p, q = pell_convergents(a, n)[n]
    return p, q, p * p - alpha * q * q


def pell_residue(a: int, n: int) -> int:
    """
    The exact value of p_n^2 - alpha q_n^2, from parity alone.

    Proved: the CF of sqrt(a(a+1)) is [a; 2, 2a, 2, 2a, ...] and applying
    x -> a^2 - alpha = -a to the standard Pell descent gives residue +1 on
    odd n and -a on even n.  Verified as an integer identity by
    `verify_theorem`, so a mistake here cannot go unnoticed.

    The parity is taken from `expected_sign` rather than re-derived, so the two
    cannot drift apart: they are the same claim, one as a residue and one as
    a sign.  This function used to skip argument validation entirely, unlike
    every other entry point, and so accepted `pell_residue(0, 2)`.
    """
    _check_a(a)
    _check_n(n)
    # +1 on odd n, -a on even n; `expected_sign` supplies the parity.
    return 1 if expected_sign(a, n) > 0 else -a


def expected_sign(a: int, n: int) -> int:
    """
    The sign of S_n = p_n - q_n sqrt(alpha), derived from the residue.

    Exact and closed-form: S_n has the sign of p_n^2 - alpha q_n^2 because
    p_n, q_n > 0.  No approximation is involved.
    """
    _check_a(a)
    if n < 0:
        raise ValueError(f"n must be >= 0, got {n}")
    return 1 if n % 2 == 1 else -1


def log2_ratio_law(a: int, n_max: int) -> List[Tuple[int, float, float]]:
    """
    log2(1/|S_n|), and its ratio to the input size N, for n = 1..n_max.

    MEASUREMENT ONLY.  Uses float; the certified values come from
    signexact.exact_sign, and the identities proved here are checked with
    exact integer arithmetic by `verify_theorem`.

    N = 2 log2 p_n + 2 log2 q_n + log2 alpha, the bit size of the two input
    radicands p_n^2 and alpha q_n^2.

    Returns a list of (n, ratio, log2_inv_S) triples.
    """
    _check_a(a)
    _check_n(n_max)

    alpha = a * (a + 1)
    sqrt_alpha = sqrt(alpha)
    cv = pell_convergents(a, n_max)
    results = []
    for n in range(1, n_max + 1):
        p, q = cv[n]
        # |S_n| = |D| / (p + q sqrt(alpha)) with D = p^2 - alpha q^2, so
        # log2(1/|S_n|) = log2(p + q sqrt(alpha)) - log2(|D|).
        d = abs(p * p - alpha * q * q)
        log2_inv_S = log2(p + q * sqrt_alpha) - log2(d)
        N = 2 * log2(p) + 2 * log2(q) + log2(alpha)
        if N <= 0:
            # Unreachable for validated inputs: a >= 2 and n >= 1 give p, q >= 1
            # and alpha >= 6, so N >= log2(6) > 0.  Reported rather than turned
            # into an `inf` sentinel, because an infinity would pass a downstream
            # `ratio > SEPARATION_RATIO` check silently -- the one way a wrong
            # measurement here could be mistaken for a good one.
            raise ValueError(
                f"log2_ratio_law: non-positive input size N={N} at a={a}, n={n}"
            )
        ratio = log2_inv_S / N
        results.append((n, ratio, log2_inv_S))
    return results


def separation_identity(a: int, n: int) -> float:
    """
    log2(1/|S_n|) - N/4, computed as the exact closed form 1 - log2(|D|).

    D = p_n^2 - alpha q_n^2 is an exact integer, so the only approximation
    anywhere is the one implicit in reading N as a real number.  Returns
    1.0 on odd n and 1 - log2(a) on even n.
    """
    _check_a(a)
    if n < 0:
        raise ValueError(f"n must be >= 0, got {n}")
    d = abs(pell_residue(a, n))
    return 1.0 - log2(d)


def mobius_iterates(a: int, n_max: int) -> List[Tuple[int, int]]:
    """
    The Möbius iterates z_n = phi^n(a+1) in lowest terms, for n = 0..n_max.

    phi(x) = a + a/(a + x), applied n times to the seed a+1.

    Returns a list of (A_n, B_n) with z_n = A_n/B_n reduced.  Exact: all
    arithmetic is in Fractions, so lowest terms is guaranteed rather than
    assumed.
    """
    _check_a(a)
    _check_n(n_max)

    out = []
    z = F(a + 1)
    for _ in range(n_max + 1):
        out.append((z.numerator, z.denominator))
        z = F(a) + F(a) / (F(a) + z)
    return out


def verify_theorem(a_max: int = 20, n_max: int = 10) -> List[str]:
    """
    Check every exact claim in this module.  Returns a list of failure
    strings; empty means all passed.

    Checked with exact integer and Fraction arithmetic throughout, except for
    check 5, which compares against float logarithms at a stated tolerance:
      1. the CF recurrence reproduces the stated partial quotients
         [a; 2, 2a, 2, 2a, ...]
      2. p^2 - alpha q^2 = +1 for odd n and = -a for even n
      3. sign(S_n) predicted by parity matches the certified decider
      4. the Möbius-CF correspondence for the pronic family
      5. log2(1/|S_n|) - N/4 == 1 - log2|D|, to 1e-3, and on odd n the ratio
         log2(1/|S_n|)/N exceeds SEPARATION_RATIO = 1/4 by ~1/N

    Check 5 is the one place a float enters, and it cannot produce a wrong
    sign: the sign comes from check 3, i.e. from the exact residue.  An earlier
    version of this docstring described the limit as 1/2, which the
    measurements refuted; the limit is 1/4, as `SEPARATION_RATIO` records.
    """
    from signexact import exact_sign

    failures: List[str] = []
    for a in range(2, a_max + 1):
        alpha = a * (a + 1)
        cv = pell_convergents(a, n_max)

        # 1. the declared CF period reproduces the recurrence.
        for n in range(1, n_max):
            a_next = 2 if (n + 1) % 2 == 1 else 2 * a
            p, q = cv[n]
            p_prev, q_prev = cv[n - 1]
            if a_next * p + p_prev != cv[n + 1][0] or a_next * q + q_prev != cv[n + 1][1]:
                failures.append(f"a={a}, n={n}: CF period [{a}; 2, 2a, ...] does not reproduce the recurrence")

        # 2. the exact residue, by parity.
        for n in range(1, n_max + 1):
            p, q = cv[n]
            diff = p * p - alpha * q * q
            want = pell_residue(a, n)
            if diff != want:
                failures.append(f"a={a}, n={n}: p^2-alpha*q^2={diff}, expected {want}")

        # 3. parity-predicted sign vs the certified decider.
        for n in range(1, n_max + 1):
            p, q = cv[n]
            got = exact_sign([(1, p * p), (-1, alpha * q * q)]).sign
            want = expected_sign(a, n)
            if got != want:
                failures.append(f"a={a}, n={n}: exact sign {got}, parity predicts {want}")

        # 4. Möbius-CF correspondence.
        mob = mobius_iterates(a, n_max)
        for n in range(n_max + 1):
            A, B = mob[n]
            if n % 2 == 1:
                if B != cv[n][0]:
                    failures.append(f"a={a}, n={n} odd: B={B}, p_n={cv[n][0]}")
                if A != alpha * cv[n][1]:
                    failures.append(f"a={a}, n={n} odd: A={A}, alpha*q_n={alpha * cv[n][1]}")
            else:
                if a * B != cv[n][0]:
                    failures.append(f"a={a}, n={n} even: a*B={a * B}, p_n={cv[n][0]}")
                if A != (a + 1) * cv[n][1]:
                    failures.append(f"a={a}, n={n} even: A={A}, (a+1)*q_n={(a + 1) * cv[n][1]}")

    # 5. the separation law.  This is the one float-based check, so it lives
    #    in its own function and says so; checks 1-4 above are exact.
    failures.extend(verify_separation_law(a_max, n_max))
    return failures


# Tolerance for the float check below.  The residual it absorbs is the o(1)
# term in g = 2 p_n + o(1), measured at 7.5e-5 over a=2..24, n=1..39 (worst
# at a=2, n=1), so this leaves about a 13x margin.  tests/test_f1_theorem.py
# re-measures that range so the margin cannot silently evaporate.
#
# The residual is now also PROVED, not just measured: PROOFS.md Theorem 3.2
# gives the exact one-sided form
#     0 < rho_n = log2(1/|S_n|) - (N_n/4 + 1 - log2|D_n|)
#             = log2((1+s_n)/(2 sqrt(s_n)))  <=  0.205 a^2 / p_n^4,
# with s_n = q_n sqrt(alpha)/p_n, and the asymptotic
# rho_n = D_n^2/(32 ln2 p_n^4)(1 + O(a/p_n^2)) -- 7.18e-5 at the worst state,
# within 5% of the measurement.  The first-order terms cancel on the two
# sides of the law, which is why the residual is second order.
_SEPARATION_TOLERANCE = 1e-3


def verify_separation_law(a_max: int = 20, n_max: int = 10) -> List[str]:
    """
    Check 5 on its own: the separation law, measured in float.

    Factored out of `verify_theorem` so that function can describe checks 1-4
    as exact without qualification, and so a reader who wants only the exact
    parts can skip this one.  Two things are compared:

        log2(1/|S_n|) - N/4  ==  1 - log2|D|     (the exact closed form)
        log2(1/|S_n|)/N      >   SEPARATION_RATIO on odd n, by ~1/N

    The right-hand side of the first is exact arithmetic; the left is float,
    and `_SEPARATION_TOLERANCE` is the margin the o(1) residual allows.  So
    this is a measurement corroborating an identity, not a proof of it.

    Nothing about the *sign* of S_n is decided here.  The sign follows from
    the exact residue law, which `verify_theorem` checks in integers.
    """
    failures: List[str] = []
    for a in range(2, a_max + 1):
        cv = pell_convergents(a, n_max)
        for n, ratio, log2_inv in log2_ratio_law(a, n_max):
            p, q = cv[n]
            N = 2 * log2(p) + 2 * log2(q) + log2(a * (a + 1))
            want = separation_identity(a, n)
            if abs((log2_inv - N / 4) - want) > _SEPARATION_TOLERANCE:
                failures.append(
                    f"a={a}, n={n}: log2(1/|S|)-N/4={log2_inv - N / 4:.6f}, "
                    f"expected 1-log2|D|={want:.6f}"
                )
            if n % 2 == 1 and n >= 5 and not (ratio > SEPARATION_RATIO):
                failures.append(
                    f"a={a}, n={n}: odd-n ratio={ratio:.4f} should exceed "
                    f"{SEPARATION_RATIO} by 1/N"
                )
    return failures


